am = np.max(sorted_data)
h = (am - a0) / m
bins = [a0 + i * h for i in range(m + 1)]
# Подсчёт частот с учётом замкнутого слева первого интервала
freq = [0] * m
for val in sorted_data:
    if val == a0:
        freq[0] += 1
        continue
    for k in range(m):
        if bins[k] < val <= bins[k + 1]:
            freq[k] += 1
            break
