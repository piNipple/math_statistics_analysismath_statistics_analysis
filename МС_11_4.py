def phi(x):
    """Плотность стандартного нормального распределения"""
    return math.exp(-x * x / 2.0) / math.sqrt(2.0 * math.pi)
def F_laplace(x):
    """Функция распределения стандартного нормального закона"""
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))
